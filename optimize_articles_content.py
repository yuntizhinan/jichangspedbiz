def process_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    original_content = content

    # Replace headings with SEO question-style headings
    for old_h, new_h in heading_replacements:
        content = content.replace(old_h, new_h)

    # Global text updates for brand consistency & clear terminology
    content = content.replace("极界", "EdgeNova")

    if content != original_content:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Updated article content: {filepath}")

def main():
    articles_dir = "articles"
    if not os.path.exists(articles_dir):
        return
    for fname in os.listdir(articles_dir):
        if fname.endswith(".html"):
            process_file(os.path.join(articles_dir, fname))

if __name__ == "__main__":
    main()
